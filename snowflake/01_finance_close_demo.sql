  (SELECT COUNT(*) FROM RESCUE_LAB_SNOWFLAKE.TRUSTED.ORDERS) AS TRUSTED_ORDERS,
  (SELECT SUM(TRUSTED_REVENUE) FROM RESCUE_LAB_SNOWFLAKE.FINANCE.DAILY_SALES) AS TRUSTED_REVENUE;
