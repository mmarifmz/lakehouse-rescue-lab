CREATE OR REPLACE DYNAMIC TABLE RESCUE_LAB_SNOWFLAKE.TRUSTED.ORDERS
  TARGET_LAG = 'DOWNSTREAM'
  WAREHOUSE = RESCUE_LAB_WH
AS
SELECT ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, CHANNEL, AMOUNT, EVENT_TS, INGESTED_AT
FROM RESCUE_LAB_SNOWFLAKE.RAW.ORDER_EVENTS
WHERE AMOUNT > 0 AND EVENT_TS IS NOT NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDER_ID ORDER BY INGESTED_AT) = 1;

CREATE OR REPLACE VIEW RESCUE_LAB_SNOWFLAKE.TRUSTED.ORDER_QUARANTINE AS
SELECT ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, CHANNEL, AMOUNT, EVENT_TS, INGESTED_AT,
  CASE WHEN COUNT(*) OVER (PARTITION BY ORDER_ID) > 1 THEN 'duplicate_order_id' END AS QUARANTINE_REASON
FROM RESCUE_LAB_SNOWFLAKE.RAW.ORDER_EVENTS
QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDER_ID ORDER BY INGESTED_AT DESC) = 1;

CREATE OR REPLACE DYNAMIC TABLE RESCUE_LAB_SNOWFLAKE.FINANCE.DAILY_SALES
  TARGET_LAG = 'DOWNSTREAM'
  WAREHOUSE = RESCUE_LAB_WH
AS
SELECT TO_DATE(EVENT_TS) AS SALES_DATE, CHANNEL, COUNT(*) AS TRUSTED_ORDER_COUNT, SUM(AMOUNT) AS TRUSTED_REVENUE
FROM RESCUE_LAB_SNOWFLAKE.TRUSTED.ORDERS
GROUP BY 1, 2;

-- The Finance reconciliation: 6 received, 5 trusted, RM997.60 reported.
